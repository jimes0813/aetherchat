export function translate(locale: UiLocale, key: TranslationKey, values: Record<string, string | number> = {}) {
  const template = resources[locale][key] || resources['zh-CN'][key] || key;
  return Object.entries(values).reduce((text, [name, value]) => text.split(`{${name}}`).join(String(value)), template as string);
}

